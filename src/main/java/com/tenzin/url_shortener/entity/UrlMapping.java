package com.tenzin.url_shortener.entity;

import java.time.Instant;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;

import org.springframework.data.domain.Persistable;

/**
 * A single short-code -> original-URL mapping. Immutable once created.
 *
 * <p>The ID is taken from the {@code url_mappings_id_seq} PostgreSQL sequence by the service
 * <em>before</em> the row is inserted, so the short code (Base62 of the ID) can be part of the
 * same single INSERT. Because the ID is assigned rather than generated by Hibernate, the entity
 * implements {@link Persistable} so Spring Data issues {@code persist()} (one INSERT) instead of
 * {@code merge()} (a SELECT followed by an INSERT).
 */
@Entity
@Table(
        name = "url_mappings",
        indexes = @Index(name = "ux_url_mappings_short_code", columnList = "short_code", unique = true))
public class UrlMapping implements Persistable<Long> {

    /** Longest Base62 encoding of a positive {@code long} (Long.MAX_VALUE = "AzL8n0Y58m7"). */
    public static final int MAX_SHORT_CODE_LENGTH = 11;

    /** Practical upper bound for URLs accepted by browsers and servers. */
    public static final int MAX_URL_LENGTH = 2048;

    @Id
    private Long id;

    @Column(name = "short_code", nullable = false, updatable = false, length = MAX_SHORT_CODE_LENGTH)
    private String shortCode;

    @Column(name = "original_url", nullable = false, updatable = false, length = MAX_URL_LENGTH)
    private String originalUrl;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /**
     * Read-only from JPA's point of view: written only by batched SQL updates in
     * {@code ClickStatsRepository}, never by saving the entity, so a stale entity can't overwrite them.
     */
    @Column(name = "click_count", nullable = false, insertable = false, updatable = false)
    private long clickCount;

    @Column(name = "last_clicked_at", insertable = false, updatable = false)
    private Instant lastClickedAt;

    @Transient
    private boolean isNew = true;

    /** Required by JPA. */
    protected UrlMapping() {
    }

    public UrlMapping(long id, String shortCode, String originalUrl, Instant createdAt) {
        this.id = id;
        this.shortCode = shortCode;
        this.originalUrl = originalUrl;
        this.createdAt = createdAt;
    }

    @PostLoad
    @PostPersist
    void markNotNew() {
        this.isNew = false;
    }

    @Override
    public Long getId() {
        return id;
    }

    @Override
    public boolean isNew() {
        return isNew;
    }

    public String getShortCode() {
        return shortCode;
    }

    public String getOriginalUrl() {
        return originalUrl;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    /** Clicks already written to PostgreSQL (excludes clicks still pending in Redis). */
    public long getClickCount() {
        return clickCount;
    }

    /** When clicks were last written for this link; accurate to the flush interval. Null if never clicked. */
    public Instant getLastClickedAt() {
        return lastClickedAt;
    }
}
